"""Fetch runtime secrets from AWS Secrets Manager (issue #13).

Production path:
  1. Store a JSON secret (see ``deploy/secrets.example.json``).
  2. EC2 instance profile may ``GetSecretValue`` on that ARN only.
  3. ``scripts/fetch_aws_secrets.py`` materializes an ephemeral env file
     (default ``/run/ito/runtime.env``, mode 0600) — not a durable `.env`.
  4. Compose reads ``ITO_ENV_FILE``; optionally the app also hydrates
     ``os.environ`` when ``ITO_AWS_SECRET_ID`` / ``ITO_AWS_SECRET_ARN`` is set.

Local development keeps using repo-root `.env` (never committed).
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any, Mapping, MutableMapping, Optional

# Keys that must live in Secrets Manager for production (not in durable .env).
PRODUCTION_SECRET_KEYS: tuple[str, ...] = (
    "GEMINI_API_KEY",
    "APIFY_API_TOKEN",
    "LINKEDIN_COOKIES",
    "POSTGRES_PASSWORD",
    "GRAFANA_ADMIN_PASSWORD",
    # Included when API auth (#3) is enabled:
    "API_KEYS_JSON",
)

# Optional companion keys often stored in the same JSON blob for Compose.
OPTIONAL_RUNTIME_KEYS: tuple[str, ...] = (
    "POSTGRES_USER",
    "POSTGRES_DB",
    "DATABASE_URL",
    "APIFY_ACTOR_ID",
    "APIFY_PROFILE_ACTOR_ID",
    "APIFY_POST_URL_ACTOR_ID",
    "GRAFANA_ADMIN_USER",
)


class AwsSecretsError(RuntimeError):
    """Raised when Secrets Manager cannot be read or the payload is invalid."""


def resolve_secret_id() -> Optional[str]:
    """Return configured secret id/ARN, or None when AWS fetch is disabled."""
    return (
        os.getenv("ITO_AWS_SECRET_ARN")
        or os.getenv("ITO_AWS_SECRET_ID")
        or None
    )


def parse_secret_string(secret_string: str) -> dict[str, str]:
    """Parse Secrets Manager ``SecretString`` as a flat string→string map."""
    try:
        payload = json.loads(secret_string)
    except json.JSONDecodeError as exc:
        raise AwsSecretsError("SecretString is not valid JSON") from exc
    if not isinstance(payload, dict):
        raise AwsSecretsError("SecretString JSON must be an object")

    out: dict[str, str] = {}
    for key, value in payload.items():
        if value is None:
            continue
        if isinstance(value, (dict, list)):
            out[str(key)] = json.dumps(value)
        else:
            out[str(key)] = str(value)
    return out


def fetch_secret_dict(
    secret_id: str,
    *,
    region_name: Optional[str] = None,
    client: Any = None,
) -> dict[str, str]:
    """Load and parse a Secrets Manager secret.

    ``client`` is injectable for tests; when omitted, a boto3 client is created.
    """
    if client is None:
        try:
            import boto3
        except ImportError as exc:  # pragma: no cover - exercised in docs, not CI without boto3
            raise AwsSecretsError(
                "boto3 is required to fetch AWS secrets. "
                "Install project requirements or use scripts/fetch_aws_secrets.py on a host with boto3."
            ) from exc
        session_kwargs: dict[str, str] = {}
        region = region_name or os.getenv("AWS_REGION") or os.getenv("AWS_DEFAULT_REGION")
        if region:
            session_kwargs["region_name"] = region
        client = boto3.client("secretsmanager", **session_kwargs)

    try:
        response = client.get_secret_value(SecretId=secret_id)
    except Exception as exc:  # noqa: BLE001 — normalize AWS errors for callers
        raise AwsSecretsError(f"GetSecretValue failed for {secret_id!r}: {exc}") from exc

    secret_string = response.get("SecretString")
    if not secret_string:
        raise AwsSecretsError(
            f"Secret {secret_id!r} has no SecretString (binary secrets are not supported)"
        )
    return parse_secret_string(secret_string)


def secret_dict_to_env_lines(secrets: Mapping[str, str]) -> str:
    """Render KEY=value lines suitable for Compose ``env_file``."""
    lines: list[str] = [
        "# Generated by scripts/fetch_aws_secrets.py — do not commit",
        "# Ephemeral runtime env from AWS Secrets Manager (issue #13)",
    ]
    for key in sorted(secrets):
        value = secrets[key]
        # Escape for dotenv-style files: wrap if whitespace/special chars present.
        if any(ch in value for ch in ('\n', '\r', '"', " ", "#", "'")) or value == "":
            escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lines.append(f'{key}="{escaped}"')
        else:
            lines.append(f"{key}={value}")
    lines.append("")
    return "\n".join(lines)


def write_env_file(secrets: Mapping[str, str], path: Path, *, mode: int = 0o600) -> Path:
    """Atomically write secrets to ``path`` with restrictive permissions."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = secret_dict_to_env_lines(secrets)
    fd, tmp_name = tempfile.mkstemp(prefix=".ito-runtime-", dir=str(path.parent), text=True)
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_path, mode)
        tmp_path.replace(path)
        # Re-apply mode after replace (some FS reset bits on rename).
        os.chmod(path, mode)
    except Exception:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)
        raise
    return path


def apply_secrets_to_environ(
    secrets: Mapping[str, str],
    environ: Optional[MutableMapping[str, str]] = None,
    *,
    override: bool = True,
) -> list[str]:
    """Copy secret keys into ``environ`` (default ``os.environ``).

    Returns the list of keys applied.
    """
    target: MutableMapping[str, str] = os.environ if environ is None else environ
    applied: list[str] = []
    for key, value in secrets.items():
        if not override and key in target and target[key] != "":
            continue
        target[key] = value
        applied.append(key)
    return applied


def load_aws_secrets_into_environ(
    *,
    secret_id: Optional[str] = None,
    region_name: Optional[str] = None,
    client: Any = None,
    override: bool = True,
) -> list[str]:
    """Fetch from AWS and apply to ``os.environ`` when a secret id is configured.

    Returns applied keys, or ``[]`` when no secret id is configured (local/dev).
    """
    resolved = secret_id if secret_id is not None else resolve_secret_id()
    if not resolved:
        return []
    secrets = fetch_secret_dict(resolved, region_name=region_name, client=client)
    return apply_secrets_to_environ(secrets, override=override)


def missing_production_secrets(secrets: Mapping[str, str]) -> list[str]:
    """Return required production keys that are absent or blank."""
    missing: list[str] = []
    for key in PRODUCTION_SECRET_KEYS:
        if key == "API_KEYS_JSON":
            # Optional until #3 auth is enabled in the environment.
            continue
        if key == "LINKEDIN_COOKIES":
            # Allowed empty when cookie-less Apify actors are used.
            continue
        value = secrets.get(key, "")
        if not str(value).strip():
            missing.append(key)
    return missing


def simulate_rotation(
    current: Mapping[str, str],
    updates: Mapping[str, str],
) -> dict[str, str]:
    """Return the secret map after a rotation update (playbook dry-run helper)."""
    rotated = dict(current)
    rotated.update(updates)
    return rotated
